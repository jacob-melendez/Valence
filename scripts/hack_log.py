"""Build the Hack OHI/O work log from git: every commit since the baseline tag, by track, with times and files.

    python scripts/hack_log.py                       # print the log
    python scripts/hack_log.py --write               # refresh the generated section of docs/HACKOHIO_LOG.md
    python scripts/hack_log.py --start 2026-10-24T12:00-04:00 --end 2026-10-25T12:00-04:00 --write

Hack OHI/O accepts a continuation of an existing project with a precise log of the work done during the event.
The baseline tag marks the project as it stood before the event; everything after it is listed here. Commit
subjects start with a track tag, e.g. "[web] Port the feature function to TypeScript"; commits outside the
--start/--end window are flagged. Merge commits are skipped (they carry no work of their own). Read-only.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

REPO = Path(__file__).resolve().parents[1]
BASE_TAG = "hackohio-2026-baseline"
BASE_SHA = "cc28be9fe5315791e8dcc715c382ae94869f61d0"  # the commit the tag points to (used if the tag isn't fetched)
LOG_FILE = REPO / "docs" / "HACKOHIO_LOG.md"
START_MARK, END_MARK = "<!-- hacklog:start -->", "<!-- hacklog:end -->"
TRACKS = {"web": "Valence Web", "emotion": "Emotion map", "eval": "Evaluation", "infra": "Infrastructure",
          "docs": "Docs", "pitch": "Pitch"}
_TAG = re.compile(r"^\[(?P<tag>[a-z0-9-]+)\]\s*")
_SEP, _END = "\x1f", "\x1e"


@dataclass
class Commit:
    sha: str
    when: datetime
    author: str
    subject: str
    files: list[tuple[str, int, int]] = field(default_factory=list)  # path, added, deleted (-1 for binary)

    @property
    def track(self) -> str:
        m = _TAG.match(self.subject)
        return m["tag"] if m else "other"

    @property
    def title(self) -> str:
        return _TAG.sub("", self.subject)

    @property
    def added(self) -> int:
        return sum(a for _, a, _ in self.files if a > 0)

    @property
    def deleted(self) -> int:
        return sum(d for _, _, d in self.files if d > 0)


def _git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True, text=True).stdout


def commits_since(repo: Path, base: str) -> list[Commit]:
    # Each record starts with _END, so a commit's numstat lines stay in its own chunk.
    fmt = _END + _SEP.join(["%H", "%aI", "%an", "%s"])
    out = _git(repo, "log", "--reverse", "--no-merges", f"--format={fmt}", "--numstat", f"{base}..HEAD")
    commits = []
    for chunk in out.split(_END)[1:]:
        head, *stat = chunk.strip("\n").splitlines()
        sha, when, author, subject = head.split(_SEP)
        commits.append(Commit(sha, datetime.fromisoformat(when), author, subject, _numstat(stat)))
    return commits


def _numstat(lines: list[str]) -> list[tuple[str, int, int]]:
    out = []
    for line in lines:
        parts = line.split("\t")
        if len(parts) == 3:
            a, d, path = parts
            out.append((path, int(a) if a != "-" else -1, int(d) if d != "-" else -1))
    return out


def render(commits: list[Commit], *, base: str, base_sha: str, tz: ZoneInfo, start: datetime | None,
           end: datetime | None, shortstat: str) -> str:
    def t(dt: datetime) -> str:
        return dt.astimezone(tz).strftime("%a %b %d %H:%M")

    outside = [c for c in commits if (start and c.when < start) or (end and c.when > end)]
    by_track: dict[str, list[Commit]] = defaultdict(list)
    for c in commits:
        by_track[c.track].append(c)
    lines = [
        f"_Generated by `scripts/hack_log.py` from git: {len(commits)} commits since `{base}` "
        f"(`{base_sha[:7]}`), times in {tz.key}._",
        "",
        f"- Window: {t(start) if start else 'not set'} → {t(end) if end else 'not set'}"
        + (f" — **{len(outside)} commit(s) outside the window** (marked ⚠)" if outside else ""),
        f"- Total change since the baseline: {shortstat.strip() or 'none'}",
        "",
        "| Track | Commits | Lines + / − |",
        "|---|---|---|",
    ]
    for tag, cs in sorted(by_track.items(), key=lambda kv: -len(kv[1])):
        lines.append(f"| {TRACKS.get(tag, tag)} | {len(cs)} | +{sum(c.added for c in cs)} / −{sum(c.deleted for c in cs)} |")
    lines += ["", "### Timeline", "", "| Time | Track | Commit | Change | Files |", "|---|---|---|---|---|"]
    for c in commits:
        flag = " ⚠" if c in outside else ""
        top = Counter({p: max(a, 0) + max(d, 0) for p, a, d in c.files}).most_common(3)
        files = ", ".join(f"`{p}`" for p, _ in top) + (f" +{len(c.files) - 3} more" if len(c.files) > 3 else "")
        lines.append(f"| {t(c.when)}{flag} | {TRACKS.get(c.track, c.track)} | `{c.sha[:7]}` {c.title} "
                     f"| +{c.added} / −{c.deleted} | {files} |")
    return "\n".join(lines) + "\n"


def write_section(path: Path, body: str) -> None:
    text = path.read_text(encoding="utf-8")
    if START_MARK not in text or END_MARK not in text:
        raise SystemExit(f"{path} has no {START_MARK} ... {END_MARK} section")
    head, rest = text.split(START_MARK, 1)
    _, tail = rest.split(END_MARK, 1)
    path.write_text(f"{head}{START_MARK}\n{body}{END_MARK}{tail}", encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--base", default=BASE_TAG, help="baseline tag or commit (default %(default)s)")
    ap.add_argument("--start", type=datetime.fromisoformat, help="hackathon start, ISO 8601 with offset")
    ap.add_argument("--end", type=datetime.fromisoformat, help="hackathon end, ISO 8601 with offset")
    ap.add_argument("--tz", default="America/New_York", help="time zone for display (default %(default)s)")
    ap.add_argument("--repo", type=Path, default=REPO)
    ap.add_argument("--log", type=Path, default=LOG_FILE)
    ap.add_argument("--write", action="store_true", help="rewrite the generated section of the log file")
    args = ap.parse_args(argv)
    try:
        base_sha = _git(args.repo, "rev-parse", f"{args.base}^{{commit}}").strip()
    except subprocess.CalledProcessError:
        if args.base != BASE_TAG:
            print(f"unknown baseline {args.base!r}", file=sys.stderr)
            return 2
        try:  # the tag is created from the Mac; a checkout without it uses the pinned commit
            base_sha = _git(args.repo, "rev-parse", f"{BASE_SHA}^{{commit}}").strip()
        except subprocess.CalledProcessError:
            print(f"unknown baseline {args.base!r} (and {BASE_SHA[:7]} not in this checkout)", file=sys.stderr)
            return 2
        args.base = base_sha
    commits = commits_since(args.repo, args.base)
    body = render(commits, base=args.base, base_sha=base_sha, tz=ZoneInfo(args.tz), start=args.start,
                  end=args.end, shortstat=_git(args.repo, "diff", "--shortstat", f"{args.base}..HEAD"))
    if args.write:
        write_section(args.log, body)
        print(f"wrote {len(commits)} commits to {args.log}")
    else:
        print(body)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
