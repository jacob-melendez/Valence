"""Generate docs/RESULTS.md from reports/metrics.json (never edit RESULTS.md by hand).

    python scripts/write_results.py
"""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
NAMES = {
    "m0": "M0 face snapshot", "m0t": "M0t face history", "m1": "M1 context snapshot",
    "m2_noface": "M2 context history, no face", "m2_abs": "M2 with absolute dB/lux (ablation)",
    "m2_notime": "M2 without the Time layer", "m2": "**M2 served (context + face history)**", "m3": "M3 GRU + attention (benchmark)",
}
ORDER = ["m0", "m0t", "m1", "m2_noface", "m2_abs", "m2_notime", "m2", "m3"]


def pct(v: float | None) -> str:
    return "—" if v is None else f"{100 * v:.1f}%"


def f2(v: float | None) -> str:
    return "—" if v is None else f"{v:.3f}"


def main() -> None:
    m = json.loads((REPO / "reports" / "metrics.json").read_text())
    states = m["states"]
    head = m.get("headline", {})
    out = [
        "# Results",
        "",
        "> Generated by `scripts/write_results.py` from `reports/metrics.json` "
        f"({m.get('generated_at', '?')}). Do not edit by hand; rerun `make eval` then the script.",
        "",
        f"**All numbers are on simulated data** ({m['test_sessions']} held-out simulator sessions, `noise_scale` "
        f"{m['noise_scale']}, untuned). They test the architecture under the behavioral assumptions published in "
        "[DATASET.md](DATASET.md) — not real-world accuracy. Session-level bootstrap: "
        f"{m['bootstrap']} resamples.",
        "",
        "## Headline",
        "",
        "| Claim | Face-only (M0) | Served (M2) |",
        "|---|---|---|",
    ]
    fr = head.get("frustrated_masked_recall", {})
    fm = head.get("focused_misread_as_negative", {})
    out += [
        f"| Masked frustration caught (Frustrated_Masked recall) | {pct(fr.get('m0'))} | {pct(fr.get('m2'))} |",
        f"| Focused people misread as a negative state (\"resting focus face\") | {pct(fm.get('m0'))} | {pct(fm.get('m2'))} |",
        f"| Macro-F1, full 15-minute window | {f2(m['models']['m0']['macro_f1'])} | {f2(m['models']['m2']['macro_f1'])} |",
    ]
    rob = m.get("robustness", {})
    if rob:
        d0 = dict(map(tuple, rob["face_dropout"]["m0"]))
        d2 = dict(map(tuple, rob["face_dropout"]["m2"]))
        l0 = dict(map(tuple, rob["low_light"]["m0"]))
        l2 = dict(map(tuple, rob["low_light"]["m2"]))
        out += [
            f"| Macro-F1 with the face hidden on every tick | {f2(d0.get(1.0))} | {f2(d2.get(1.0))} |",
            f"| Macro-F1 at 10% light (face readings degraded) | {f2(l0.get(0.1))} | {f2(l2.get(0.1))} |",
        ]
    cal = m.get("calibration_m2", {})
    out += ["", f"Calibration (M2, temperature {cal.get('temperature', float('nan')):.2f}): expected calibration error "
            f"{f2(cal.get('ece_before'))} before, {f2(cal.get('ece_after'))} after temperature scaling.", ""]

    out += ["## Proof 2 — context over time beats a face snapshot", "",
            "![Accuracy vs history](../reports/figs/accuracy_vs_history.png)", "",
            "| Model | " + " | ".join(f"{p['minutes']} min" for p in m["accuracy_vs_history"]["m2"]) + " |",
            "|---|" + "---|" * len(m["accuracy_vs_history"]["m2"])]
    for key in ORDER:
        if key in m["accuracy_vs_history"]:
            pts = m["accuracy_vs_history"][key]
            out.append(f"| {NAMES[key]} | " + " | ".join(
                f"{p['macro_f1']:.3f}" + (f" [{p['ci95'][0]:.2f}, {p['ci95'][1]:.2f}]" if p["ci95"][0] != p["ci95"][1] else "")
                for p in pts) + " |")
    out += ["", "Macro-F1 by minutes of history in the rolling window (95% CI in brackets). The face-only model is flat "
            "by construction; the context models gain from the window.", "",
            "![Confusion matrices](../reports/figs/confusion_m0_vs_m2.png)", "",
            "### Full model ladder (full 15-minute window)", "",
            "| Model | Macro-F1 | Balanced accuracy | " + " | ".join(f"Recall {s}" for s in states) + " |",
            "|---|---|---|" + "---|" * len(states)]
    for key in ORDER:
        e = m["models"].get(key)
        if not e or "recall" not in e:
            continue
        out.append(f"| {NAMES[key]} | {e['macro_f1']:.3f} | {e['balanced_accuracy']:.3f} | "
                   + " | ".join(pct(e["recall"].get(s)) for s in states) + " |")
    if "m3" in m["models"]:
        out += ["", f"M3 (GRU + attention over raw ticks, trained on {m['models']['m3'].get('device', '?')}): macro-F1 "
                f"{m['models']['m3']['macro_f1_mixed_history']:.3f} on mixed-history test windows. Benchmark only; M2 is served "
                "because its TreeSHAP attributions drive the explanations."
                + (" Its curve peaks before the full window and then drops, which suggests it is under-trained on long "
                   "sequences within the training budget; treat it as a lower bound." if m["accuracy_vs_history"].get("m3")
                   and m["accuracy_vs_history"]["m3"][-1]["macro_f1"] < max(p["macro_f1"] for p in m["accuracy_vs_history"]["m3"]) - 0.03
                   else ""), "",
                "![Which minutes mattered](../reports/figs/m3_attention.png)"]
    age = m.get("accuracy_by_episode_age", [])
    if age:
        out += ["", "### Where context is weak: the first minute of a new episode", "",
                "![Accuracy by episode age](../reports/figs/acc_vs_episode_age.png)", "",
                "| Time since the episode began | Windows | M0 | M1 | M2 |", "|---|---|---|---|---|"]
        out += [f"| {r['bin']} | {r['n']} | {pct(r.get('m0'))} | {pct(r.get('m1'))} | {pct(r.get('m2'))} |" for r in age]
        out += ["", "Context lags behavior: in the first 30 seconds of a new emotional episode the served model is less "
                "accurate than the face alone. This is the honest cost of a context model, and why the override and label "
                "changes use hysteresis."]
    if rob:
        out += ["", "## Proof 3 — stable when face evidence is missing or degraded", "",
                "Only the face channel is degraded; every context channel (including the lux feature) is unchanged.", "",
                "![Face dropout](../reports/figs/robustness_face_dropout.png)", "",
                "| Share of ticks with the face hidden | " + " | ".join(NAMES[k].strip('*') for k in ("m0", "m0t", "m2_noface", "m2")) + " |",
                "|---|---|---|---|---|"]
        for i, (level, _) in enumerate(rob["face_dropout"]["m0"]):
            out.append(f"| {int(level * 100)}% | " + " | ".join(f"{rob['face_dropout'][k][i][1]:.3f}" for k in ("m0", "m0t", "m2_noface", "m2")) + " |")
        out += ["", "![Low light](../reports/figs/robustness_lux.png)", "",
                "| Relative light level | " + " | ".join(NAMES[k].strip('*') for k in ("m0", "m0t", "m2_noface", "m2")) + " |",
                "|---|---|---|---|---|"]
        for i, (level, _) in enumerate(rob["low_light"]["m0"]):
            out.append(f"| {level:g} | " + " | ".join(f"{rob['low_light'][k][i][1]:.3f}" for k in ("m0", "m0t", "m2_noface", "m2")) + " |")
        out += ["", "Scope of this claim: decision stability when face evidence is missing or degraded. It is not a measurement "
                "of demographic bias; the upstream face and pose detectors' fairness evaluations are in their own model cards "
                "(see [MODEL_CARD.md](MODEL_CARD.md))."]
    legacy = m.get("legacy_mock")
    if legacy:
        out += ["", "## Why the original mock dataset was replaced", "",
                "| Trained on the original mock data (i.i.d. rows) | Accuracy |", "|---|---|",
                f"| Face column only | {pct(legacy['face_only'])} |", f"| Context columns only | {pct(legacy['context_only'])} |",
                f"| All columns | {pct(legacy['full'])} |", "",
                "Context alone was perfectly separable and rows had no time structure, so the original data could not test "
                "the 15-minute window. Simulator v2 adds time structure, overlap, noise and missing modalities "
                "([DATASET.md](DATASET.md))."]
    shift = m.get("venue_shift")
    if shift:
        names = {"m2": "M2 served (room-relative)", "m2_abs": "M2 with absolute dB/lux", "legacy": "Previous served M2"}
        venues = [r["venue_db"] for r in shift["m2"]]
        out += ["", "## Venue shift: a loud hall is not a frustrated person", "",
                "Focused ticks read as a negative state when the test sessions are mixed with constant hall noise "
                "(0 = the session's own room). The served model reads the room relative to the venue baseline "
                "captured on arrival (`POST /api/room/baseline`).", "",
                "| Model | " + " | ".join("own room" if v == 0 else f"+{v} dB hall" for v in venues) + " |",
                "|---|" + "---|" * len(venues)]
        for key in ("m2", "m2_abs", "legacy"):
            if key in shift:
                out.append(f"| {names[key]} | " + " | ".join(pct(r["focused_misread_as_negative"]) for r in shift[key]) + " |")
        out += ["", "![venue shift](../reports/figs/venue_shift.png)"]
    out += ["", "## Ablations", "",
            f"- With absolute dB/lux instead of room-relative levels: macro-F1 "
            f"{f2(m['models'].get('m2_abs', {}).get('macro_f1'))} vs {f2(m['models']['m2']['macro_f1'])} on the "
            "simulator's own rooms; see the venue shift above for what absolute levels cost in a loud hall.",
            f"- Without the Time layer (hours since break, time of day): {f2(m['models'].get('m2_notime', {}).get('macro_f1'))} — "
            "an operator-set break clock is not what drives the label.", "",
            m.get("disclosure", ""), ""]
    (REPO / "docs" / "RESULTS.md").write_text("\n".join(out))
    print("wrote docs/RESULTS.md")


if __name__ == "__main__":
    main()
